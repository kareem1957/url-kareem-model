"""
Dataset downloader for phishing URL detection.

Downloads and caches:
  1. PhiUSIIL Phishing URL Dataset (UCI ML Repository, 2024)
     - 235,795 labeled URLs (legit + phishing)
     - Citation: Prasad & Chandra (2024), Computers & Security
  2. Tranco top 100k domains (legitimate, diverse reference set)
     - tranco-list.eu, generated by aggregating multiple ranking lists

The script is idempotent: re-running skips files already present.
Output files land in data/raw/ and are consumed by the data loader
in src/data/loaders.py (next phase).

Run from project root:
    python scripts/download_datasets.py
"""
from __future__ import annotations

import hashlib
import sys
import zipfile
from pathlib import Path

import httpx
from tqdm import tqdm

# Make the project root importable when the script is run directly
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from config.settings import settings  # noqa: E402
from src.utils.logger import get_logger  # noqa: E402


logger = get_logger(__name__)


# --------------------------------------------------------------------------- #
# Data sources                                                                #
# --------------------------------------------------------------------------- #

PHIUSIIL_URL = (
    "https://archive.ics.uci.edu/static/public/967/"
    "phiusiil+phishing+url+dataset.zip"
)
PHIUSIIL_ZIP_NAME = "phiusiil.zip"

TRANCO_URL = "https://tranco-list.eu/top-1m.csv.zip"
TRANCO_ZIP_NAME = "tranco_top1m.zip"

DOWNLOAD_CHUNK_SIZE = 65_536  # 64 KB chunks

# Timeout strategy: we DO NOT cap total download time. UCI and similar
# academic servers are often slow (200-500 KB/s) and a 50 MB file can
# legitimately take 3+ minutes. Instead we time out only when no bytes
# arrive for `read` seconds, which kills genuinely stalled connections
# but tolerates slow ones.
HTTP_TIMEOUT = httpx.Timeout(
    connect=15.0,   # establishing TCP+TLS
    read=60.0,      # max gap between received chunks
    write=15.0,     # we don't write much, but for completeness
    pool=15.0,      # waiting for a free connection from the pool
)


# --------------------------------------------------------------------------- #
# Helpers                                                                     #
# --------------------------------------------------------------------------- #

def _sha256(path: Path) -> str:
    """Compute SHA-256 of a file."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(DOWNLOAD_CHUNK_SIZE), b""):
            h.update(chunk)
    return h.hexdigest()


def _download(url: str, destination: Path, description: str) -> Path:
    """
    Download url to destination with a progress bar.

    Idempotent: if destination already exists and is non-empty, skip.
    Uses streaming so memory stays low even for large files.
    """
    if destination.exists() and destination.stat().st_size > 0:
        logger.info(
            "download_skipped_already_present",
            path=str(destination),
            size_bytes=destination.stat().st_size,
        )
        return destination

    destination.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = destination.with_suffix(destination.suffix + ".part")

    logger.info("download_starting", url=url, destination=str(destination))

    try:
        with httpx.stream(
            "GET",
            url,
            timeout=HTTP_TIMEOUT,
            follow_redirects=True,
            headers={"User-Agent": "PhishingDetector-DatasetDownloader/1.0"},
        ) as response:
            response.raise_for_status()
            total = int(response.headers.get("content-length", 0))

            with tmp_path.open("wb") as f, tqdm(
                total=total,
                unit="B",
                unit_scale=True,
                desc=description,
                ascii=True,
            ) as bar:
                for chunk in response.iter_bytes(
                    chunk_size=DOWNLOAD_CHUNK_SIZE
                ):
                    f.write(chunk)
                    bar.update(len(chunk))
    except httpx.HTTPError as exc:
        if tmp_path.exists():
            tmp_path.unlink()
        logger.error("download_failed", url=url, error=str(exc))
        raise

    tmp_path.replace(destination)

    logger.info(
        "download_complete",
        path=str(destination),
        size_bytes=destination.stat().st_size,
        sha256=_sha256(destination)[:16],
    )
    return destination


def _extract_zip(zip_path: Path, extract_to: Path) -> list[Path]:
    """Extract a zip archive. Returns list of extracted file paths."""
    extract_to.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(zip_path) as zf:
        members = zf.namelist()
        logger.info(
            "extract_starting",
            archive=str(zip_path),
            member_count=len(members),
        )

        extracted: list[Path] = []
        for member in members:
            # Defense against zip-slip (malicious path traversal)
            member_path = (extract_to / member).resolve()
            if not str(member_path).startswith(str(extract_to.resolve())):
                raise RuntimeError(
                    f"Unsafe zip member path detected: {member}"
                )
            zf.extract(member, extract_to)
            extracted.append(extract_to / member)

    logger.info("extract_complete", archive=str(zip_path))
    return extracted


# --------------------------------------------------------------------------- #
# Pipeline                                                                    #
# --------------------------------------------------------------------------- #

def download_phiusiil() -> Path:
    """Download and extract PhiUSIIL. Returns the extracted CSV path."""
    raw_dir = settings.raw_data_dir
    zip_path = raw_dir / PHIUSIIL_ZIP_NAME

    _download(PHIUSIIL_URL, zip_path, "PhiUSIIL")
    _extract_zip(zip_path, raw_dir / "phiusiil")

    csv_files = list((raw_dir / "phiusiil").glob("*.csv"))
    if not csv_files:
        raise RuntimeError(
            "PhiUSIIL zip extracted but no CSV file found inside."
        )
    return csv_files[0]


def download_tranco() -> Path:
    """Download and extract Tranco top-1m. Returns the extracted CSV path."""
    raw_dir = settings.raw_data_dir
    zip_path = raw_dir / TRANCO_ZIP_NAME

    _download(TRANCO_URL, zip_path, "Tranco")
    _extract_zip(zip_path, raw_dir / "tranco")

    csv_files = list((raw_dir / "tranco").glob("*.csv"))
    if not csv_files:
        raise RuntimeError(
            "Tranco zip extracted but no CSV file found inside."
        )
    return csv_files[0]


def main() -> int:
    """Download all datasets. Returns exit code."""
    from config.logging_config import configure_logging
    configure_logging()

    settings.raw_data_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 60)
    print("Phishing URL Detection - Dataset Downloader")
    print("=" * 60)
    print()

    try:
        phiusiil_csv = download_phiusiil()
        print(f"\nPhiUSIIL ready at: {phiusiil_csv}")

        tranco_csv = download_tranco()
        print(f"Tranco ready at:   {tranco_csv}")

        print("\nAll datasets downloaded successfully.")
        return 0
    except Exception as exc:
        logger.error("dataset_download_failed", error=str(exc))
        print(f"\nERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())